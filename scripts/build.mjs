#!/usr/bin/env node
// Builds both halves with tsdown:
//   lib/index.js  — Host plugin, ESM, deps external.
//   lib/client.js — Web client plugin, wrapped as one window.__ModuleLoader__
//                   factory (the format DSH's client loader expects; see the
//                   official @deepseek-ai/dsh-client-ui-* packages).
// lib/ is committed so local-checkout and git installs need no build step.
import { build } from 'tsdown'
import { readFileSync, writeFileSync, rmSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const lib = join(root, 'lib')
rmSync(lib, { recursive: true, force: true })

const external = [/^@deepseek-ai\//, /^@astryxdesign\//, /^esbuild$/, /^react($|\/)/, /^react-dom($|\/)/]

await build({
  cwd: root,
  config: false,
  entry: { index: 'src/index.ts' },
  format: 'esm',
  platform: 'node',
  target: 'node22',
  outDir: 'lib',
  dts: true,
  clean: false,
  external,
  fixedExtension: false,
  logLevel: 'warn',
})

await build({
  cwd: root,
  config: false,
  entry: { client: 'client/index.tsx' },
  format: 'cjs',
  platform: 'neutral',
  target: 'es2022',
  outDir: join('lib', '.client-tmp'),
  dts: false,
  clean: false,
  external,
  fixedExtension: false,
  logLevel: 'warn',
})

const tmp = join(lib, '.client-tmp')
const cjs = readFileSync(join(tmp, 'client.cjs'), 'utf8').replace(/^"use strict";\s*/, '')
const indent = (s) => s.split('\n').map((l) => (l ? '\t\t' + l : l)).join('\n')
const wrapped = `// GENERATED by scripts/build.mjs — do not edit. Source: client/index.tsx
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${indent(cjs.trimEnd())}
\t\treturn module.exports;
\t}
});
`
writeFileSync(join(lib, 'client.js'), wrapped)
rmSync(tmp, { recursive: true, force: true })
console.log('built lib/index.js, lib/index.d.ts, lib/client.js')
